from __future__ import annotations

import os

# ---------------------------------------------------------------- パス
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MESH_PATH = os.path.join(ROOT, "mesh", "cube_lc005_hex.msh")
RESULT_DIR = os.path.join(ROOT, "results")
FIGURE_DIR = os.path.join(ROOT, "figures")

# ---------------------------------------------------------------- 媒質
RHO = 1.205          # 空気密度 [kg/m^3]
C0 = 343.5           # 音速 [m/s]
Z0 = RHO * C0        # 特性インピーダンス [Pa*s/m]

# ---------------------------------------------------------------- 解析条件
FREQ = 1000.0        # 解析周波数 [Hz]（論文 §4.1）
H_MESH = 0.05        # 要素サイズ [m]（1 辺 1 m の立方体を 20 分割）

# ---------------------------------------------------------------- 境界条件
# IMP: スカラアドミタンス境界（垂直入射で無反射）
Y_IMP = 1.0 / Z0

# PML: 2 乗プロファイル、s_xi = 1 + i*sigma(xi)/k
SIGMA_MAX = 50.0             # 最大吸収係数 [1/m]
PML_LAYERS_ALL = (1, 2, 3, 4)  # 層数スイープ（4 層＝収束参照）
PML_REF_LAYERS = 4

# Prop: 提案手法（C_r = 0 の非局所境界条件）
PROP_N_K = None      # 波数サンプル数 M。None で各面の境界節点数（= 441）に一致
PROP_WHITEN = True   # F_Gamma のホワイトニング（F^H W F ≈ I）
PROP_EIG_EPS = 1e-12    # 固有値カットオフ（絶対）
PROP_EIG_REL = 1e-10    # 固有値カットオフ（最大固有値比）
GMRES_TOL = 1e-8        # 収束判定の許容残差（論文 §2.3）
GMRES_RESTART = 200
GMRES_MAXITER = 200

# 提案手法（直接法）で密行列 B_hat を陽に構成する際の波数サンプル数。
# メモリ比較（直接法 149 MB → GMRES 71 MB）の根拠としてのみ使用する。
PROP_DIRECT_N_K = 2000

# ---------------------------------------------------------------- 無限要素（参考）
# 論文本文では比較対象から外したが、評価指標の共通スケール s の推定に
# 計算当時の全手法を用いているため、数値再現のために実装を残している。
IE_ORDER = 4         # 動径方向次数 p
IE_L = 0.2           # マッピングパラメータ
IE_SMAX = IE_L * 3   # 動径方向の積分範囲
IE_NGAUSS = 30

# ---------------------------------------------------------------- 評価
EVAL_R_MIN = 5 * H_MESH   # 0.25 m：音源近傍の離散化誤差を除外
EVAL_R_MAX = 0.45         # 0.45 m：最寄り境界面から 1 要素内側
W_BIN = 0.05              # W-bar を評価する球殻の幅 [m]
W_PERCENTILE = (25, 75)   # 四分位幅

# 共通スケール s を推定する手法の集合（論文の数値はこの集合で得られている）
SCALE_METHODS = ("IMP", "IE4", "Prop", "PML4")

# ---------------------------------------------------------------- 数値許容値
EPS_DETJ = 1e-18     # ヤコビアン行列式の下限
TOL_BC = 1e-8        # 境界節点判定の座標許容値
